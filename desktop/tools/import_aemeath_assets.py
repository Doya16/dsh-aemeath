"""Maintainer tool: import the 爱弥斯 expression presets and the chosen voice lines from an asset-workbench export.

Usage:
  python tools/import_aemeath_assets.py --export <workbench>/export/aemeath-<stamp> [--presets 鸭牌,雾雪,Stephen]
  python tools/import_aemeath_assets.py --audio-only --export <workbench>/export/aemeath-<stamp>
  python tools/import_aemeath_assets.py --index P:/Aemeath/表情包/_清单/导入索引.json

- --index writes resources/emoji-index.json, the compact SHA-256 index the zip importer uses to name images
  downloaded from 呜哇小站 (artist, pack, clean name, skip). It holds names and hashes only, no images.

- bindings.json (format aemeath-pet-materials v2) lists the GIF presets; every event has gifs[<preset>] and
  shared audio_clips. Presets whose name contains 测试 are left out unless named with --presets.
- Each preset GIF is copied byte for byte to assets/originals/<code>-<state>.gif, so its SHA-256 stays the one
  the 呜哇小站 download has (the zip importer skips such copies). assets/catalog.json lists them with artist and pack.
- Every preset must use 16 different GIFs for its 16 events (compared by SHA-256).
- aemeath_pet/packs.py (generated) holds PACKS, PACK_LABELS and DEFAULT_PACK.
- The chosen voice lines become OGG files with a subtitle .txt in defaults/audio/爱弥斯语音, and
  defaults/settings.json gets the voice pools and the default preset.
Needs ffmpeg on PATH and Pillow.
"""
import argparse, hashlib, json, pathlib, re, shutil, subprocess, sys
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
FFMPEG = shutil.which('ffmpeg') or 'ffmpeg'
STATES = ['pet', 'doubleclick', 'hover', 'drag', 'drop', 'feed', 'idle', 'thinking', 'reading', 'writing', 'working',
          'waiting', 'done', 'error', 'paused', 'unknown']
# preset name -> catalog id prefix (stable: installed settings refer to these ids)
CODES = {'鸭牌': 'yp', '雾雪': 'wx', 'Stephen': 'st'}
AUDIO_DIR = '爱弥斯语音'
# OGG name -> SHA-256 of the exported WAV it was encoded from (maintainer record; not shipped)
SOURCES = ROOT / 'tools' / 'voice-sources.json'


def sha(p):
    return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()


def gif_info(p):
    with Image.open(p) as im:
        n = getattr(im, 'n_frames', 1); durs = []
        for i in range(n):
            im.seek(i); durs.append(int(im.info.get('duration', 100) or 100))
        return im.size, n, durs


def chosen_presets(man, wanted):
    names = [p['name'] for p in man['presets']]
    if wanted:
        missing = [n for n in wanted if n not in names]
        if missing: raise SystemExit(f'not in the export: {missing}; it has {names}')
        return wanted
    return [n for n in names if '测试' not in n]


def import_gifs(export, man, presets):
    out = ROOT / 'assets' / 'originals'; out.mkdir(parents=True, exist_ok=True)
    for old in out.glob('*.gif'): old.unlink()
    catalog, packs = [], {}
    for preset in presets:
        code = CODES.get(preset) or re.sub(r'[^a-z0-9]', '', preset.lower())[:4] or f'p{len(packs) + 1}'
        info = next(p for p in man['presets'] if p['name'] == preset)
        packs[preset] = {}; seen = {}
        for state in STATES:
            g = man['events'][state].get('gifs', {}).get(preset)
            if not g: raise SystemExit(f'{preset}: no GIF for {state}')
            src = export / g['file']; digest = sha(src)
            if digest in seen: raise SystemExit(f'{preset}: {state} uses the same GIF as {seen[digest]} ({g["name"]})')
            seen[digest] = state
            gid = f'{code}-{state}'; dst = out / f'{gid}.gif'; shutil.copyfile(src, dst)
            (w, h), frames, durs = gif_info(dst)
            catalog.append({'id': gid, 'name': g['name'] + '.gif', 'pack': g.get('pack_title') or g.get('pack') or '', 'skin': preset,
                            'artist': g.get('artist') or info.get('artist') or '', 'source_url': g.get('source_url') or '',
                            'path': f'assets/originals/{gid}.gif', 'sha256': digest, 'width': w, 'height': h, 'frames': frames,
                            'duration_ms': sum(durs), 'durations_ms': durs})
            packs[preset][state] = gid
    (ROOT / 'assets' / 'catalog.json').write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    return catalog, packs


def write_packs(man, presets, packs):
    default = man.get('default_preset') if man.get('default_preset') in presets else presets[0]
    labels = {p['name']: p['name'] if p['name'] == p['artist'] else f"{p['name']} · {p['artist']}" for p in man['presets'] if p['name'] in presets}
    lines = ['"""Generated by tools/import_aemeath_assets.py from the asset-workbench export; do not edit by hand."""',
             f'# export: {man.get("created_at", "")}',
             'PACKS={']
    for preset in presets:
        body = ','.join(f"{s}='{packs[preset][s]}'" for s in STATES)
        lines.append(f" {preset!r}:dict({body}),")
    lines += ['}', 'PACK_LABELS=' + json.dumps(labels, ensure_ascii=False), f'DEFAULT_PACK={default!r}', '']
    (ROOT / 'aemeath_pet' / 'packs.py').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    return default


def seconds(path):
    """Decoded length, never the container's claim (a length header can be wrong)."""
    r = subprocess.run([FFMPEG, '-hide_banner', '-loglevel', 'error', '-i', str(path), '-f', 's16le', '-ac', '1', '-ar', '48000', '-'],
                       capture_output=True, check=True)
    return len(r.stdout) / 2 / 48000


def import_audio(export, man):
    """Encode the exported lines. A line whose exported WAV is unchanged (tools/voice-sources.json) keeps its OGG
    byte for byte, so a release only replaces the lines that really changed (see tools/make_voice_repair.py)."""
    out = ROOT / 'defaults' / 'audio'
    target = out / AUDIO_DIR; target.mkdir(parents=True, exist_ok=True)
    known = json.loads(SOURCES.read_text(encoding='utf-8')) if SOURCES.exists() else {}
    clips, n, record, kept, encoded = {}, 0, {}, set(), 0
    for state in STATES:
        e = man['events'][state]; clips[state] = []
        for i, c in enumerate(e.get('audio_clips', []), 1):
            n += 1
            title = f'{n:03}-{e["label"].split(" /")[0].split("/")[0].strip()}{i}'
            title = re.sub(r'[\\/:*?"<>|\s]+', '', title)
            dst = target / f'{title}.ogg'; src = export / c['file']; digest = sha(src)
            if not (dst.exists() and known.get(dst.name) == digest):
                # bitexact: the same WAV always gives the same OGG (no random stream serial, no encoder tag)
                subprocess.run([FFMPEG, '-hide_banner', '-loglevel', 'error', '-y', '-i', str(src), '-c:a', 'libvorbis', '-q:a', '6',
                                '-fflags', '+bitexact', '-flags:a', '+bitexact', str(dst)], check=True)
                if abs(seconds(dst) - seconds(src)) > 0.03:
                    raise SystemExit(f'{dst.name}: encoded length differs from {c["file"]}')
                encoded += 1
            dst.with_suffix('.txt').write_text(c['subtitle'] + '\n', encoding='utf-8', newline='\n')
            record[dst.name] = digest; kept |= {dst.name, dst.with_suffix('.txt').name}
            clips[state].append({'file': f'{AUDIO_DIR}/{dst.name}', 'subtitle': c['subtitle'], 'title': title, 'enabled': True})
    for old in out.iterdir():
        if old.is_dir() and old != target: shutil.rmtree(old)
        elif old.is_file(): old.unlink()
    for old in target.iterdir():
        if old.name not in kept: old.unlink()
    SOURCES.write_text(json.dumps(record, ensure_ascii=False, indent=1) + '\n', encoding='utf-8', newline='\n')
    print(f'voice lines {n}, re-encoded {encoded}')
    return clips


def write_defaults(clips, default=None):
    p = ROOT / 'defaults' / 'settings.json'
    d = json.loads(p.read_text(encoding='utf-8'))
    for state, b in d['bindings'].items():
        b.pop('asset', None)  # the GIF comes from the selected preset
        pool = clips.get(state, [])
        b['audio_clips'] = pool
        if pool:
            b['bubble_mode'] = 'audio'; b['bubble_text'] = pool[0]['subtitle']
        else:
            # The previous character's lines must not survive; fall back to the neutral built-in status text
            if b.get('bubble_mode') in ('custom', 'audio'): b['bubble_mode'] = 'auto'
            b['bubble_text'] = ''
        b.pop('audio_file', None)
    if default: d['pack'] = default
    p.write_text(json.dumps(d, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')


def write_index(source):
    data = json.loads(pathlib.Path(source).read_text(encoding='utf-8'))
    if data.get('format') != 'aemeath-emoji-index': raise SystemExit('not an aemeath-emoji-index file')
    keep = ('artist', 'pack', 'slug', 'name', 'skip')
    images = {h: {k: e.get(k, '') for k in keep} for h, e in sorted(data['images'].items())}
    out = {'format': 'aemeath-emoji-index', 'version': 1, 'source': data.get('source', 'https://emoji.wuwa.games/'),
           'note': '按 SHA-256 识别呜哇小站「打包下载」里的图片；只含名称和哈希，不含图片。',
           'packs': data.get('packs', []), 'images': images}
    target = ROOT / 'resources' / 'emoji-index.json'
    target.write_text(json.dumps(out, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8', newline='\n')
    print(f'index: {len(images)} images, {len(out["packs"])} packs -> {target.relative_to(ROOT)} ({target.stat().st_size // 1024} KB)')


def main():
    if '--index' in sys.argv:
        write_index(sys.argv[sys.argv.index('--index') + 1]); return
    ap = argparse.ArgumentParser(); ap.add_argument('--export', required=True)
    ap.add_argument('--presets', help='comma-separated preset names (default: every preset without 测试 in its name)')
    ap.add_argument('--audio-only', action='store_true', help='only the voice lines; GIFs, presets and the catalog stay as they are')
    a = ap.parse_args(); export = pathlib.Path(a.export)
    man = json.loads((export / 'bindings.json').read_text(encoding='utf-8'))
    if man.get('format') != 'aemeath-pet-materials' or man.get('version') != 2: raise SystemExit('not an aemeath-pet-materials v2 export')
    if man.get('errors'): raise SystemExit(f'the export reports errors: {man["errors"]}')
    clips = import_audio(export, man)
    if a.audio_only:
        write_defaults(clips); print(f'clips {sum(len(v) for v in clips.values())}'); return
    presets = chosen_presets(man, [x.strip() for x in a.presets.split(',')] if a.presets else None)
    catalog, packs = import_gifs(export, man, presets)
    default = write_packs(man, presets, packs)
    write_defaults(clips, default)
    print(f'presets {presets} (default {default})  gifs {len(catalog)}  clips {sum(len(v) for v in clips.values())}')


if __name__ == '__main__':
    main()
